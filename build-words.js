#!/usr/bin/env node
// Builds words.js from the plain-text lists in wordlist/.
//
//   node build-words.js
//
// Each list is named <level>-<n>.txt (level = easy, medium or hard) and has
// one entry per line:  word|part of speech|definition
// Lines starting with # and blank lines are ignored.
//
// The script checks every entry and stops with a list of problems if any
// entry is malformed, too short, or appears in more than one level.
// A word repeated within the same level is reported and only kept once.

const fs = require("fs");
const path = require("path");

const LEVELS = ["easy", "medium", "hard"];
const POS = new Set(["noun", "verb", "adjective", "adverb"]);
const MIN_LENGTH = 4;

const listDir = path.join(__dirname, "wordlist");
const outFile = path.join(__dirname, "words.js");

const errors = [];
const warnings = [];
const byWord = new Map(); // word -> entry

const files = fs.readdirSync(listDir).filter((f) => f.endsWith(".txt")).sort();

for (const file of files) {
  const level = file.split("-")[0].replace(".txt", "");
  if (!LEVELS.includes(level)) {
    errors.push(`${file}: file name must start with easy-, medium- or hard-`);
    continue;
  }

  const lines = fs.readFileSync(path.join(listDir, file), "utf8").split("\n");
  lines.forEach((raw, i) => {
    const line = raw.trim();
    if (!line || line.startsWith("#")) return;
    const where = `${file}:${i + 1}`;

    const parts = line.split("|");
    if (parts.length !== 3) {
      errors.push(`${where}: expected word|pos|definition, got "${line}"`);
      return;
    }
    const [word, pos, definition] = parts.map((p) => p.trim());

    if (!/^[a-z]+$/.test(word)) errors.push(`${where}: "${word}" must be lowercase letters only`);
    if (word.length < MIN_LENGTH) errors.push(`${where}: "${word}" is shorter than ${MIN_LENGTH} letters`);
    if (!POS.has(pos)) errors.push(`${where}: "${word}" has unknown part of speech "${pos}"`);
    if (definition.length < 8 || !/[.!?]$/.test(definition)) {
      errors.push(`${where}: "${word}" needs a full definition ending in a period`);
    }

    const prev = byWord.get(word);
    if (prev) {
      if (prev.level === level) {
        warnings.push(`${where}: "${word}" repeats ${prev.where}; kept the first`);
      } else {
        errors.push(`${where}: "${word}" is ${level} here but ${prev.level} at ${prev.where}`);
      }
      return;
    }
    byWord.set(word, { word, pos, level, definition, where });
  });
}

for (const w of warnings) console.warn("warning: " + w);
if (errors.length) {
  for (const e of errors) console.error("error: " + e);
  console.error(`\n${errors.length} problem(s) found; words.js was not written.`);
  process.exit(1);
}

const entries = [...byWord.values()].sort(
  (a, b) => LEVELS.indexOf(a.level) - LEVELS.indexOf(b.level) || a.word.localeCompare(b.word)
);

const counts = Object.fromEntries(LEVELS.map((l) => [l, entries.filter((e) => e.level === l).length]));

const out = [
  "// Word list for Hangman. GENERATED by build-words.js from wordlist/*.txt;",
  "// edit those files and rerun `node build-words.js` instead of editing this one.",
  "//",
  "// Each entry: word (lowercase letters), part of speech, commonness level",
  '// ("easy" everyday, "medium" less common, "hard" rare), and a definition.',
  "// This is a .js file (not .json) so the game works when index.html is",
  "// opened directly from disk, without a web server.",
  `// ${entries.length} words: ${counts.easy} easy, ${counts.medium} medium, ${counts.hard} hard.`,
  "const WORDS = [",
  ...entries.map(
    (e) => "  " + JSON.stringify({ word: e.word, pos: e.pos, level: e.level, definition: e.definition }) + ","
  ),
  "];",
  "",
].join("\n");

fs.writeFileSync(outFile, out);
console.log(`Wrote words.js: ${entries.length} words (${counts.easy} easy, ${counts.medium} medium, ${counts.hard} hard).`);
